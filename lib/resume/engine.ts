export function generateGoogleXYZBullet(
  portfolio: PortfolioArtifact,
  date: string = new Date().toISOString().split('T')[0]
): ResumeBulletPoint {
  const techList = Array.isArray(portfolio?.techStack) ? portfolio.techStack : [];
  const techStr = techList.length > 0 ? ` using ${techList.join(', ')}` : '';
  const title = (portfolio?.title || 'System Enhancement').trim();
  const impact = (portfolio?.impact || '').trim();
  const challenge = (portfolio?.challengeSolved || '').trim();

  // Action verb based on engineering scope
  const actionVerb = title.toLowerCase().includes('reconnection') || title.toLowerCase().includes('layer')
    ? 'Architected'
    : title.toLowerCase().includes('migration') || title.toLowerCase().includes('schema')
    ? 'Engineered'
    : title.toLowerCase().includes('rate limiter') || title.toLowerCase().includes('security')
    ? 'Implemented'
    : 'Designed and deployed';

  // Construct Google XYZ: Accomplished [X] as measured by [Y] by doing [Z]
  let bullet: string;
  if (impact && challenge) {
    bullet = `${actionVerb} ${title.toLowerCase()}${techStr}, resolving "${challenge}" and achieving ${impact.toLowerCase().replace(/\.$/, '')}.`;
  } else if (impact) {
    bullet = `${actionVerb} ${title.toLowerCase()}${techStr}, achieving ${impact.toLowerCase().replace(/\.$/, '')}.`;
  } else {
    bullet = `${actionVerb} ${title.toLowerCase()}${techStr} to enhance production system reliability.`;
  }

  // Ensure first character is uppercase
  bullet = bullet.charAt(0).toUpperCase() + bullet.slice(1);

  return {
    id: `bullet-${Date.now()}-${Math.random().toString(36).substring(2, 7)}`,
    bullet,
    category: techList.includes('WebSockets') || techList.includes('Redis')
      ? 'Distributed Systems'
      : techList.includes('PostgreSQL')
      ? 'Database & Reliability'
      : 'Core Infrastructure',
    verifiedTech: techList,
    rawFormula: {
      action: `${actionVerb} ${title}`,
      impact: impact || 'Enhanced system capability',
      tech: techList.join(', ') || 'TypeScript',
    },
    date,
  };
}

export function generateQuarterlyBragDoc(
  portfolioItems: PortfolioArtifact[],
  decisions: DecisionItem[] = []
): string {
  const items = Array.isArray(portfolioItems) ? portfolioItems : [];
  const adrs = Array.isArray(decisions) ? decisions : [];

  const techSet = new Set<string>();
  items.forEach((item) => {
    (item.techStack || []).forEach((t) => techSet.add(t));
  });

  const lines: string[] = [
    '# Engineering Brag Document & Quarterly Impact Review',
    `*Generated by ShipLog Autonomous Sub-Agent • Updated ${new Date().toISOString().split('T')[0]}*`,
    '',
    '## 🚀 Projects Shipped & Core Impact',
  ];

  if (items.length === 0) {
    lines.push('- *No shipped projects recorded in this timeframe.*');
  } else {
    items.forEach((item) => {
      lines.push(`### ${item.title}`);
      if (item.impact) lines.push(`- **Measured Impact:** ${item.impact}`);
      if (item.challengeSolved) lines.push(`- **Engineering Problem Solved:** ${item.challengeSolved}`);
      if (item.techStack && item.techStack.length > 0) {
        lines.push(`- **Grounded Tech Stack:** ${item.techStack.join(', ')}`);
      }
      lines.push('');
    });
  }

  lines.push('## 🏛️ Architectural Decisions & Tradeoffs');
  if (adrs.length === 0) {
    lines.push('- *No architectural decisions recorded in this timeframe.*');
  } else {
    adrs.forEach((adr, idx) => {
      lines.push(`### ADR #${idx + 1}: ${adr.decision}`);
      lines.push(`- **Rationale & Tradeoff:** ${adr.rationale}`);
      if (adr.evidence) lines.push(`- **Code Evidence Anchor:** \`${adr.evidence}\``);
      lines.push('');
    });
  }

  lines.push('## 🛠️ Technologies Mastered');
  if (techSet.size === 0) {
    lines.push('- *Continuous engineering across primary stack.*');
  } else {
    lines.push(Array.from(techSet).map((t) => `- **${t}**`).join('\n'));
  }

  return lines.join('\n');
}

export function synthesizeUpdatedResume(
  baseResume: string = DEFAULT_BASE_RESUME,
  newBullets: ResumeBulletPoint[] = []
): ResumeRevision {
  const bulletsToAdd = Array.isArray(newBullets) ? newBullets : [];
  let updatedMarkdown = baseResume;

  if (bulletsToAdd.length > 0) {
    const formattedBullets = bulletsToAdd.map((b) => `- ${b.bullet}`).join('\n');
    const targetAnchor = '### Senior Software Engineer | CloudScale Systems (2024 - Present)';

    if (updatedMarkdown.includes(targetAnchor)) {
      updatedMarkdown = updatedMarkdown.replace(
        targetAnchor,
        `${targetAnchor}\n${formattedBullets}`
      );
    } else {
      updatedMarkdown = `${updatedMarkdown}\n\n## Recent Verified Ships (ShipLog)\n${formattedBullets}`;
    }
  }

  // Calculate ATS Score based on Action Verbs & Metrics
  let atsScore = 88;
  const combinedText = updatedMarkdown.toLowerCase();
  if (combinedText.includes('architected') || combinedText.includes('engineered')) atsScore += 3;
  if (combinedText.includes('reduced') || combinedText.includes('achieving')) atsScore += 2;
  if (combinedText.includes('websocket') || combinedText.includes('redis')) atsScore += 2;
  atsScore = Math.min(98, Math.max(85, atsScore));

  return {
    originalMarkdown: baseResume,
    updatedMarkdown,
    newBullets: bulletsToAdd,
    atsScore,
    lastUpdated: new Date().toISOString().split('T')[0],
  };
}
